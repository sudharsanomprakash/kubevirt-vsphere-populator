// TestQemuReadsOurStreams checks the test encoder against qemu-img, an
// independent VMDK implementation: qemu-img must convert our streams back to
// the original raw bytes.
func TestQemuReadsOurStreams(t *testing.T) {
	qemu := testutil.RequireQemuImg(t)
	dir := t.TempDir()
	for _, opts := range []WriterOptions{{}, {ShuffleSeed: 5}} {
		raw := makeRaw(t, 3*1024*1024+7*512, 21)
		in := filepath.Join(dir, "in.vmdk")
		out := filepath.Join(dir, "out.raw")
		if err := os.WriteFile(in, encode(t, raw, opts), 0o600); err != nil {
			t.Fatal(err)
		}
		if b, err := exec.Command(qemu, "convert", "-f", "vmdk", "-O", "raw", in, out).CombinedOutput(); err != nil {
			t.Fatalf("qemu-img convert: %v: %s", err, b)
		}
		got, err := os.ReadFile(out)
		if err != nil {
			t.Fatal(err)
		}
		if !bytes.Equal(got, raw) {
			t.Fatalf("qemu-img output differs from source (opts %+v)", opts)
		}
	}
}

// TestRejectsQemuFileLayout documents that qemu-img's streamOptimized files
// are not streamed-export layouts: qemu-img stores the grain directory in the
// overhead area (header gdOffset is set), and writes neither a footer nor an
// end-of-stream marker. Without an end-of-stream marker a stream truncated on
// a grain boundary cannot be detected, so the decoder rejects this layout.
func TestRejectsQemuFileLayout(t *testing.T) {
	qemu := testutil.RequireQemuImg(t)
	dir := t.TempDir()
	raw := makeRaw(t, 1024*1024, 77)
	src := filepath.Join(dir, "src.raw")
	vmdkPath := filepath.Join(dir, "qemu.vmdk")
	if err := os.WriteFile(src, raw, 0o600); err != nil {
		t.Fatal(err)
	}
	if b, err := exec.Command(qemu, "convert", "-f", "raw", "-O", "vmdk", "-o", "subformat=streamOptimized", src, vmdkPath).CombinedOutput(); err != nil {
		t.Fatalf("qemu-img convert: %v: %s", err, b)
	}
	f, err := os.Open(vmdkPath)
	if err != nil {
		t.Fatal(err)
	}
	defer f.Close()
	_, err = Decode(f, DecodeOptions{})
	if err == nil || !strings.Contains(err.Error(), "grain directory at the end") {
		t.Fatalf("qemu-img file layout: got %v, want rejection", err)
	}
}

// TestVMwareGeneratedSample decodes a streamOptimized VMDK generated by VMware
// software (from the QEMU test suite, fetched by hack/fetch-fixtures.sh) and
// compares it with qemu-img's conversion and with the data pattern the QEMU
// test asserts.
func TestVMwareGeneratedSample(t *testing.T) {
	path := testutil.Fixture(t, "iotest-version3.vmdk.bz2")
	f, err := os.Open(path)
	if err != nil {
		t.Fatal(err)
	}
	defer f.Close()
	stream, err := io.ReadAll(bzip2.NewReader(f))
	if err != nil {
		t.Fatal(err)
	}
	var img []byte
	res, err := Decode(bytes.NewReader(stream), DecodeOptions{Sink: sinkFunc(func(off int64, data []byte) error {
		if img == nil {
			img = make([]byte, 64<<20) // only the first 64 MiB are checked below
		}
		if off < int64(len(img)) {
			copy(img[off:], data)
		}
		return nil
	})})
	if err != nil {
		t.Fatalf("decode VMware sample: %v", err)
	}
	if res.Header.Version != 3 || res.VirtualSize() != 16<<30 || res.Header.GrainSize != 128 {
		t.Fatalf("unexpected header %+v", res.Header)
	}
	if res.Descriptor.CreateType != "streamOptimized" || res.Descriptor.DDB["ddb.virtualHWVersion"] != "8" {
		t.Fatalf("unexpected descriptor %+v", res.Descriptor)
	}
	if !res.Ordered || res.GTMarkers == 0 || res.GDMarkers != 1 || res.Footer == nil {
		t.Fatalf("unexpected layout: %+v", res)
	}
	// qemu-iotests 059: sector i*10 grains + i sectors holds byte 0x30+i%10.
	for i := int64(0); i < 100; i++ {
		off := i*64*1024*10 + i*512
		if off+512 > int64(len(img)) {
			break
		}
		want := bytes.Repeat([]byte{byte(0x30 + i%10)}, 512)
		if !bytes.Equal(img[off:off+512], want) {
			t.Fatalf("pattern mismatch at offset %d", off)
		}
	}
	ra, err := DecodeAt(bytes.NewReader(stream), int64(len(stream)), *res.Footer, DecodeOptions{})
	if err != nil || !bytes.Equal(ra.Digest, res.Digest) {
		t.Fatalf("DecodeAt on VMware sample: %v", err)
	}

	qemu := testutil.RequireQemuImg(t)
	dir := t.TempDir()
	in := filepath.Join(dir, "sample.vmdk")
	out := filepath.Join(dir, "sample.raw")
	if err := os.WriteFile(in, stream, 0o600); err != nil {
		t.Fatal(err)
	}
	if b, err := exec.Command(qemu, "convert", "-f", "vmdk", "-O", "raw", in, out).CombinedOutput(); err != nil {
		t.Fatalf("qemu-img convert: %v: %s", err, b)
	}
	of, err := os.Open(out)
	if err != nil {
		t.Fatal(err)
	}
	defer of.Close()
	qd, err := digest.Reader(of, res.VirtualSize(), 0)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(qd, res.Digest) {
		t.Fatal("qemu-img conversion of the VMware sample differs from the Go decoder")
	}
}

type sinkFunc func(off int64, data []byte) error

func (f sinkFunc) Grain(off int64, data []byte) error { return f(off, data) }
