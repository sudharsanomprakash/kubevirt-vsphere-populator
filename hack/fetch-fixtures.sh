#!/usr/bin/env bash
# Fetches third-party test fixtures that are not redistributed in this
# repository. Each file is pinned by URL (a fixed upstream tag) and SHA-256.
set -euo pipefail
cd "$(dirname "$0")/.."
mkdir -p testdata/external

fetch() {
  local name=$1 url=$2 sha=$3
  local dst="testdata/external/$name"
  if [[ -f "$dst" ]] && echo "$sha  $dst" | sha256sum -c --quiet - 2>/dev/null; then
    return 0
  fi
  curl -fsSL --retry 3 -o "$dst.tmp" "$url"
  echo "$sha  $dst.tmp" | sha256sum -c --quiet -
  mv "$dst.tmp" "$dst"
  echo "fetched $name"
}

# A streamOptimized (version 3) VMDK generated by VMware software, used by the
# QEMU iotests (test 059). QEMU is GPL-2.0-or-later licensed; the file is
# downloaded for testing only and is not committed here.
fetch iotest-version3.vmdk.bz2 \
  https://raw.githubusercontent.com/qemu/qemu/v10.1.0/tests/qemu-iotests/sample_images/iotest-version3.vmdk.bz2 \
  924c05b1a1cf61cfd33722349dcfe59eb65cd702f363e8e114362954edba5d34
